function applyLanguage(lang) {
  const selected = translations[lang] ? lang : "id";
  const dict = translations[selected];

  document.documentElement.lang = selected === "id" ? "id" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dict[key] !== undefined) element.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
    const pairs = element.dataset.i18nAttr.split(";");
    pairs.forEach((pair) => {
      const [attribute, key] = pair.split(":");
      if (attribute && key && dict[key] !== undefined) element.setAttribute(attribute, dict[key]);
    });
  });

  document.querySelectorAll(".lang-btn").forEach((button) => {
    const active = button.dataset.lang === selected;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  const page = document.body.dataset.page;
  if (page === "home") document.title = dict.page_home_title;
  if (page === "projects") document.title = dict.page_projects_title;
  if (page === "certificates") document.title = dict.page_certificates_title;

  localStorage.setItem("portfolio-language", selected);
}

document.querySelectorAll(".lang-btn").forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

